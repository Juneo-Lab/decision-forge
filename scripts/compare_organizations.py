"""Build several organizations' specifications and compare how each decides the same situations.

Every decision cites the policy sentence that governs it, so a reader can see that a different answer
comes from a different organizational standard, not from a different model or prompt.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from decision_forge.io import canonical, load_project
from decision_forge.models import Episode, Project
from decision_forge.pipeline import build, load_run
from decision_forge.policy import governing_rule


def decision(project: Project, episode: Episode) -> dict[str, str]:
    """The chosen candidate and the rule, with its quotation, that allowed it."""
    choice = episode.valid_choices[0]
    verdict = next(v for v in episode.verdicts if v.candidate_id == choice)
    rule = governing_rule(project.select_rules(verdict.matched_rules), verdict)
    if rule is None:
        raise ValueError(f"No rule governs {choice} in {episode.id}")
    return {"choice": choice, "rule": rule.id, "quote": rule.evidence[0].quote}


def _situations(project: Project) -> Any:
    """Everything that defines the situations a build samples; rules are deliberately excluded."""
    nodes = [node.model_dump(mode="json", exclude={"rule_ids"}) for node in project.nodes]
    recipe = project.recipe
    sampling = (recipe.seed, recipe.variants_per_scenario, recipe.candidate_pool_per_scenario)
    return nodes, [scenario.model_dump(mode="json") for scenario in project.scenarios], sampling


def compare(specs: list[Path], workspace: Path) -> dict[str, Any]:
    """Build each specification and align decisions by node and situation."""
    organizations: list[dict[str, str]] = []
    rows: dict[tuple[str, str], dict[str, Any]] = {}
    projects = [load_project(spec) for spec in specs]
    reference = projects[0]
    for project in projects[1:]:
        if _situations(project) != _situations(reference):
            raise ValueError("The specifications must declare the same nodes, scenarios, and dimensions")
    dimensions = {node.id: node.dimensions for node in reference.nodes}
    for spec, project in zip(specs, projects, strict=True):
        organizations.append({"id": project.organization.id, "name": project.organization.name})
        run = workspace / project.organization.id
        build(spec, run, cache=workspace / ".forge-cache")
        for episode in load_run(run):
            if len(episode.valid_choices) != 1:
                raise ValueError(f"{project.organization.id} has no single best choice for {episode.id}")
            declared = dimensions.get(episode.node_id, [])
            situation = {d.path.removeprefix("state."): episode.intervention[d.path] for d in declared}
            order = [d.values.index(episode.intervention[d.path]) for d in declared]
            key = (episode.node_id, canonical(situation))
            row = rows.setdefault(
                key, {"node_id": episode.node_id, "situation": situation, "order": order, "decisions": {}}
            )
            row["decisions"][project.organization.id] = decision(project, episode)
    ids = [org["id"] for org in organizations]
    aligned = list(rows.values())
    node_order = [node.id for node in reference.nodes]
    aligned.sort(key=lambda row: (node_order.index(row["node_id"]), row["order"]))
    for row in aligned:
        row["differs"] = len({row["decisions"][org]["choice"] for org in ids}) > 1
    questions = {node.id: node.question for node in reference.nodes}
    return {"organizations": organizations, "questions": questions, "rows": aligned}


def _plain(value: Any) -> str:
    return value if isinstance(value, str) else canonical(value)


def render_markdown(result: dict[str, Any]) -> str:
    organizations = result["organizations"]
    different = sum(row["differs"] for row in result["rows"])
    lines = [
        "# Same agent action, different organizations",
        "",
        "Generated by `scripts/compare_organizations.py`; do not edit by hand.",
        "",
        f"{len(result['rows'])} situations, {different} decided differently. Every decision cites the "
        "policy sentence that governs it.",
    ]
    for node_id, question in result["questions"].items():
        lines += [
            "",
            f"## {question}",
            "",
            "| Situation | " + " | ".join(org["name"] for org in organizations) + " |",
            "| --- | " + " | ".join("---" for _ in organizations) + " |",
        ]
        for row in (r for r in result["rows"] if r["node_id"] == node_id):
            situation = ", ".join(
                f"{key.replace('_', ' ')}: `{_plain(value)}`" for key, value in row["situation"].items()
            )
            marker = " **≠**" if row["differs"] else ""
            cells = [
                f"**{row['decisions'][org['id']]['choice']}**: “{row['decisions'][org['id']]['quote']}”"
                for org in organizations
            ]
            lines.append(f"| {situation}{marker} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("specs", type=Path, nargs="+", help="Two or more project specifications")
    parser.add_argument("--workspace", type=Path, required=True, help="New directory for the builds")
    parser.add_argument("--markdown", type=Path, help="Write the comparison table here")
    args = parser.parse_args()
    if len(args.specs) < 2:
        parser.error("Compare at least two specifications")
    if args.workspace.exists() and any(args.workspace.iterdir()):
        parser.error("Choose a new or empty workspace directory")
    comparison = compare(args.specs, args.workspace)
    text = render_markdown(comparison)
    if args.markdown:
        args.markdown.write_text(text, encoding="utf-8")
    print(text)
